def _typo(text: str) -> str:
    """French typography: a thin no-break space before : ; ? ! and inside « »."""
    for mark in (":", ";", "?", "!", "»"):
        text = text.replace(" " + mark, " " + mark)
    return text.replace("« ", "« ")


